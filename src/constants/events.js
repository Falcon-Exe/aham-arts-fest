export const isGroupEvent = (eventName) => {
    if (!eventName) return false;
    return GROUP_EVENTS.includes(eventName.trim().toUpperCase());
};

export const getEventType = (eventName) => {
    if (!eventName) return "Unknown";
    const name = eventName.trim().toUpperCase();
    if (EVENT_MAP[name]) return EVENT_MAP[name];
    if (GENERAL_LIST.includes(name)) return "General";
    return "Unknown";
};

export const getGeneralSubtype = (eventName) => {
    if (!eventName) return "Off Stage";
    const name = eventName.trim().toUpperCase();
    return GENERAL_SUBTYPE_MAP[name] || "Off Stage";
};

export const isGeneralEvent = (eventName) => {
    if (!eventName) return false;
    return GENERAL_LIST.includes(eventName.trim().toUpperCase());
};

export const getEventScope = (eventName) => {
    if (!eventName) return "Common/General";
    const name = eventName.trim().toUpperCase();
    if (GENERAL_LIST.includes(name)) return "Common/General";
    return EVENT_SCOPE_MAP[name] || "Junior & Senior";
};

export const resolveClassCategory = (studentClass, studentCategory) => {
    if (studentClass) {
        const upper = String(studentClass).toUpperCase().trim();
        if (upper.includes("THAMHEEDIYYA") || upper.includes("THAMHIDIYYA")) {
            return "Junior";
        }
        if (upper.includes("ALIYA") || upper.includes("AALIYA")) {
            return "Senior";
        }
    }
    if (studentCategory && studentCategory !== "Junior & Senior" && studentCategory !== "Junior/Senior") {
        let cat = String(studentCategory).trim();
        if (cat === "Common/General" || cat === "Common / General") return "General";
        return cat;
    }
    return "General";
};

